# -*- coding: utf-8 -*-
"""The docs cannot drift from the config model: every YAML example with a ``tasks:`` key in the
docs and the step docstrings is a complete config that ``load_project()`` accepts, and every step
has a docstring for its docs page (generated by ``docs/conf.py``)."""

import ast
import re
from pathlib import Path

import click
import pytest
from ruamel.yaml import YAML

from snappy_pipeline.apps.snappy_cli import main

from snappy_pipeline.orchestration import ON_HOLD_STEPS, load_project
from snappy_pipeline.workflow_registry import WORKFLOW_REGISTRY

ROOT = Path(__file__).parents[2]

#: A fenced YAML block in Markdown, also as MyST ``code-block`` directive
MD_YAML = re.compile(r"^```(?:\{code-block\} )?ya?ml\n(.*?)^```", re.MULTILINE | re.DOTALL)
#: An RST ``code-block:: yaml`` directive with its indentation
RST_YAML = re.compile(r"^( *)\.\. code-block:: ya?ml\n", re.MULTILINE)


def _rst_blocks(text: str) -> list[str]:
    """Return the content of the ``code-block:: yaml`` directives in ``text``."""
    blocks = []
    for match in RST_YAML.finditer(text):
        indent = len(match.group(1))
        lines = []
        for line in text[match.end() :].splitlines():
            if line.strip() and len(line) - len(line.lstrip()) <= indent:
                break
            lines.append(line)
        blocks.append("\n".join(lines))
    return blocks


def _sources():
    """Yield the hand-written docs and the step module docstrings, with their kind."""
    docs = [*ROOT.glob("README.md"), *ROOT.glob("CONTRIBUTING.md"), *ROOT.glob("docs/*.md")]
    for path in sorted([*docs, *ROOT.glob("docs/*.rst")]):
        yield path.relative_to(ROOT), path.suffix, path.read_text()
    for path in sorted(ROOT.glob("snappy_pipeline/workflows/*/__init__.py")):
        if doc := ast.get_docstring(ast.parse(path.read_text())):
            yield path.relative_to(ROOT), ".rst", doc


def _yaml_blocks():
    for path, kind, text in _sources():
        blocks = MD_YAML.findall(text) if kind == ".md" else _rst_blocks(text)
        for i, block in enumerate(blocks):
            yield pytest.param(block, id=f"{path}-{i}")


BLOCKS = list(_yaml_blocks())


def test_docs_have_task_examples():
    assert sum("tasks:" in block.values[0] for block in BLOCKS) > 3


@pytest.mark.parametrize("block", BLOCKS)
def test_yaml_example_is_valid(block, tmp_path):
    """Every YAML example parses; one with a ``tasks`` key is a complete config."""
    config = YAML(typ="safe").load(block)
    if isinstance(config, dict) and "tasks" in config:
        load_project({"data_sets": {}, **config}, str(tmp_path))


@pytest.mark.parametrize("step", sorted(set(WORKFLOW_REGISTRY) - ON_HOLD_STEPS))
def test_step_docstring_starts_with_a_title(step):
    path = ROOT / "snappy_pipeline" / "workflows" / step / "__init__.py"
    doc = ast.get_docstring(ast.parse(path.read_text())) or ""
    title = doc.partition("\n")[0]
    assert title and not title.endswith("."), f"{step}: docstring needs a title line"


def _subcommands(group, prefix="snappy"):
    for name, command in group.commands.items():
        if isinstance(command, click.Group):
            yield from _subcommands(command, f"{prefix} {name}")
        elif not command.hidden:
            yield f"{prefix} {name}"


def test_usage_lists_every_subcommand():
    """The subcommand table of the usage page lists exactly the commands of ``snappy``."""
    table = re.findall(
        r"^\| `(snappy [a-z -]+?)`", (ROOT / "docs/usage.md").read_text(), re.MULTILINE
    )
    assert sorted(table) == sorted(_subcommands(main))
