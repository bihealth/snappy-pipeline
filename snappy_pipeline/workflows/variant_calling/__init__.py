class GetResultFilesMixin:
    """Mixin to provide ``get_result_files()`` function for variant calling and
    variant annotation steps.

    The function will use ``get_output_files()`` for all actions to obtain
    the files in the ``output/directory`` to expect from the given step.
    """

    @listify
    def get_result_files(self) -> SnakemakeListItemsGenerator:
        """Return concrete result file paths"""

        def strip_tpl(tpl):
            return tpl.replace(r",[^\.]+", "")

        group_by = self.parent.effective_group_by
        members = self.parent.cohort_members if group_by == "cohort" else {}

        for action in self.actions:
            output_files = self.get_output_files(action).values()
            result_paths_tpls = [
                strip_tpl(p) for p in flatten(output_files) if p.startswith("output/")
            ]
            for path_tpl in result_paths_tpls:
                for entity_name in self.parent.output_entities:
                    kwargs = {}
                    if "index_library_name" in path_tpl:
                        kwargs["index_library_name"] = [entity_name]
                        # Find member libs for this cohort's primary library.
                        for cohort_name, member_libs in members.items():
                            if entity_name in member_libs:
                                kwargs["donor_library_name"] = member_libs
                                break
                    else:
                        kwargs["library_name"] = [entity_name]
                    for key, value in self.get_extra_kv_pairs().items():
                        if "{%s}" % key in path_tpl:
                            kwargs[key] = value
                    yield from expand(
                        path_tpl,
                        **kwargs,
                    )

    def get_extra_kv_pairs(self):
        return {}


class VariantCallingGetLogFileMixin:
    """Mixin to provide the generic ``get_log_file()`` function for variant calling"""

    @dictify
    def get_log_file(self, action) -> SnakemakeDictItemsGenerator:
        """Return dict of log files in the "log" directory."""
        _ = action
        token = "{library_name}"
        prefix = f"work/{token}/log/{token}.{self.name}_{action}"
        key_ext = (
            ("log", ".log"),
            ("conda_info", ".conda_info.txt"),
            ("conda_list", ".conda_list.txt"),
            ("wrapper", ".wrapper.py"),
            ("env_yaml", ".environment.yaml"),
        )
        for key, ext in key_ext:
            yield key, f"{prefix}{ext}"
            yield f"{key}_md5", f"{prefix}{ext}.md5"


class VariantCallingStepPart(GetResultFilesMixin, VariantCallingGetLogFileMixin, BaseStepPart):
    """Base class for germline variant calling step parts

    Variant calling is performed on a per-pedigree level.  The (single) index individual is used
    for naming the output file.
    """

    #: Class available actions
    actions = ("run",)

    def __init__(self, parent):
        super().__init__(parent)
        self.base_path_out = "work/{index_library_name}/out/{index_library_name}{ext}"
        self.base_path_tmp = self.base_path_out.replace("/out/", "/tmp/")

    def get_input_files(self, action) -> SnakemakeDict:
        self._validate_action(action)
        return getattr(self, f"_get_input_files_{action}")

    @dictify
    def _get_input_files_run(self, wildcards) -> SnakemakeDictItemsGenerator:
        df = self.parent.build_library_dataframe()
        if df.empty:
            return

        group_by = self.parent.effective_group_by or "cohort"

        # Determine the target libraries based on the wildcard
        if group_by == "cohort":
            # wildcards.library_name is the index library name; find its cohort
            df_target = df[
                df["library_name"].isin(self.parent.get_cohort_libraries(wildcards.library_name))
            ]
        elif group_by == "library":
            # Per-library logic
            df_target = df[df["library_name"] == wildcards.library_name]
        else:
            raise ValueError(f"Unknown group_by: {group_by}")

        selection = getattr(self.config, "library_selection", None)
        if selection:
            from snappy_pipeline.workflows.abstract import apply_library_selection

            # Note: "kind" logic isn't strictly necessary if selection encompasses it, but we can assume default 'germline' if needed
            df_target = apply_library_selection(df_target, selection, "germline")

        if df_target["kind"].eq("cancer").all():
            yield "ped", []
        else:
            if group_by == "cohort":
                yield (
                    "ped",
                    f"work/write_pedigree.{wildcards.library_name}/out/{wildcards.library_name}.ped",
                )
            else:
                cohort_name = df_target.iloc[0]["cohort_name"]
                yield "ped", f"work/write_pedigree.{cohort_name}/out/{cohort_name}.ped"

        bams = []
        for _, row in df_target.iterrows():
            infix = row["library_name"]
            bams.append(self.parent.upstream("ngs_mapping")(f"output/{infix}/out/{infix}.bam"))
        yield "bam", bams

    def get_output_files(self, action) -> SnakemakeDict:
        self._validate_action(action)
        return getattr(self, f"_get_output_files_{action}")()

    @dictify
    def _get_output_files_run(self) -> SnakemakeDictItemsGenerator:
        token = "{library_name}"
        work_files = {
            "vcf": f"work/{token}/out/{token}.vcf.gz",
            "vcf_md5": f"work/{token}/out/{token}.vcf.gz.md5",
            "vcf_tbi": f"work/{token}/out/{token}.vcf.gz.tbi",
            "vcf_tbi_md5": f"work/{token}/out/{token}.vcf.gz.tbi.md5",
        }
        yield from work_files.items()
        yield (
            "output_links",
            [
                re.sub(r"^work/", "output/", work_path)
                for work_path in chain(work_files.values(), self.get_log_file("run").values())
            ],
        )


class BcftoolsCallStepPart(VariantCallingStepPart):
    """Germline variant calling with bcftools"""

    #: Step name
    name = "bcftools_call"

    def get_resource_usage(self, action: str, **kwargs) -> ResourceUsage:
        self._validate_action(action)
        return ResourceUsage(
            threads=16,
            runtime="2d",
            mem=f"{int(3.75 * 1024 * 16)}MB",
        )

    @dictify
    def _get_input_files_run(self, wildcards: Wildcards) -> SnakemakeDictItemsGenerator:
        parent = super()._get_input_files_run(wildcards)
        for k, v in parent.items():
            yield k, v
        yield "reference", self.parent.w_config.static_data_config.reference.path
        yield "reference_index", self.parent.w_config.static_data_config.reference.path + ".fai"

    def get_args(self, action: str):
        self._validate_action(action)

        reference_path = self.parent.w_config.static_data_config.reference.path
        if "GRCh37" in reference_path or "hg19" in reference_path:
            assembly = "GRCh37"
        elif "GRCh38" in reference_path or "hg38" in reference_path:
            assembly = "GRCh38"
        else:
            assembly = "unknown"

        return {
            "assembly": assembly,
            "ignore_chroms": self.config.ignore_chroms,
            "window_length": self.config.bcftools_call.window_length,
            "num_threads": self.config.bcftools_call.num_threads,
            "max_depth": self.config.bcftools_call.max_depth,
            "max_indel_depth": self.config.bcftools_call.max_indel_depth,
        }


class GatkCallerStepPartBase(VariantCallingStepPart):
    """Base class for GATK v3/v4 variant callers"""

    @dictify
    def _get_input_files_run(self, wildcards: Wildcards) -> SnakemakeDictItemsGenerator:
        """
        Adds the reference & dbsnp input files to the bams & pedigree.
        Note that dpsnp is not needed by combine & genotype sub-steps of GATK4 hc,
        but the previous code was checking for the presence of dbsnp, so
        when was failing when dbsnp is not present anyway.
        """
        yield from super()._get_input_files_run(wildcards).items()
        yield "reference", self.parent.w_config.static_data_config.reference.path
        yield "dbsnp", self.parent.w_config.static_data_config.dbsnp.path

    def get_resource_usage(self, action: str, **kwargs) -> ResourceUsage:
        self._validate_action(action)
        num_threads = self.config[self.name].num_threads
        mem_per_thread = 5.5
        mem_total = int(mem_per_thread * num_threads + 0.5)
        return ResourceUsage(
            threads=num_threads,
            runtime="2d",
            mem=f"{mem_total}GB",
        )


